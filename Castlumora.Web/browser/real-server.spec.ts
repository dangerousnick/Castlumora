// Opt-in verification against a disposable LOOPBACK server. Never point at production.
import { test,expect } from '@playwright/test';
const server=process.env.CASTLUMORA_TEST_SERVER;
const username=process.env.CASTLUMORA_TEST_USER;
const password=process.env.CASTLUMORA_TEST_PASSWORD;
test('real disposable server: authenticate, browse, details, stream and report progress',async({page})=>{
  test.skip(!server||!username||password===undefined,'Set the documented disposable-server test environment.');
  if(!['127.0.0.1','localhost','[::1]'].includes(new URL(server!).hostname))throw new Error('Real-server tests require a disposable loopback server.');
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('Server address').fill(server!);
  await page.getByRole('button',{name:'Connect',exact:true}).click();
  await page.getByLabel('Username').fill(username!);
  await page.getByLabel('Password',{exact:true}).fill(password!);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('link',{name:'Browse',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Browse',exact:true}).click();
  await page.getByRole('link',{name:/Details for /}).first().click();
  await expect(page.locator('.detail-copy h1')).toBeVisible();
  const started=page.waitForResponse(r=>r.url().includes('/Sessions/Playing')&&!r.url().includes('/Progress')&&r.request().method()==='POST');
  await page.getByRole('link',{name:/^(Watch now|Resume)$/}).click();
  await expect.poll(()=>page.locator('video').evaluate((v:HTMLVideoElement)=>v.currentTime),{timeout:20000}).toBeGreaterThan(0);
  expect((await started).ok()).toBe(true);
  const progress=page.waitForResponse(r=>r.url().includes('/Sessions/Playing/Progress')&&r.request().method()==='POST');
  await page.locator('video').evaluate((v:HTMLVideoElement)=>v.pause());
  expect((await progress).ok()).toBe(true);
  const stopped=page.waitForResponse(r=>r.url().includes('/Sessions/Playing/Stopped')&&r.request().method()==='POST');
  await page.getByRole('link',{name:'Back',exact:true}).click();
  expect((await stopped).ok()).toBe(true);
  expect(errors).toEqual([]);
});
